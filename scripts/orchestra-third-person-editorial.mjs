export function applyThirdPersonEditorial(record) {
  const spec = revisions.find((x) => x.id === record.id && x.path === record.path);
  if (spec) {
    for (const { index, needle, now } of spec.changes) {
      const prior = record.paragraphs[index];
      if (typeof prior !== "string" || !prior.includes(needle))
        throw new Error("THIRD_PERSON_EDITORIAL_SOURCE_DRIFT_" + spec.id + "_" + index);
      record.paragraphs[index] = now;
    }
    if (spec.title) {
      if (record.title !== spec.title[0]) throw new Error("THIRD_PERSON_TITLE_SOURCE_DRIFT_" + spec.id);
      record.title = spec.title[1];
    }
  }
  if (record.kind === "product") {
    record.paragraphs = record.paragraphs.map((p) => {
      for (const change of patronBoilerplate) if (p === change.old) return change.now;
      return p;
    });
  }
  return record;
}

